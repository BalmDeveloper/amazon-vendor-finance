-- Snowflake setup for snowflake-agent-hub.
-- Run as ACCOUNTADMIN. Reuses the existing MCP server
-- SALES_INTELLIGENCE.DATA.SALES_INTELLIGENCE_MCP (tool: sales_intelligence_agent).

USE ROLE ACCOUNTADMIN;

-- 1. App schema + tables
CREATE SCHEMA IF NOT EXISTS SALES_INTELLIGENCE.APP;

CREATE TABLE IF NOT EXISTS SALES_INTELLIGENCE.APP.CHATS (
  ID STRING PRIMARY KEY,
  TITLE STRING,
  SANDBOX_ID STRING,
  CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS SALES_INTELLIGENCE.APP.MESSAGES (
  ID STRING PRIMARY KEY,
  CHAT_ID STRING,
  ROLE STRING,              -- user | assistant
  CONTENT STRING,
  EVENTS VARIANT,           -- tool calls, charts, action items emitted during the turn
  CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS SALES_INTELLIGENCE.APP.ACTION_ITEMS (
  ID STRING PRIMARY KEY,
  CHAT_ID STRING,
  TITLE STRING,
  DETAIL STRING,
  OWNER STRING,
  PRIORITY STRING,          -- low | medium | high
  STATUS STRING DEFAULT 'open',
  DUE_DATE DATE,
  CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS SALES_INTELLIGENCE.APP.DASHBOARDS (
  ID STRING PRIMARY KEY,
  NAME STRING,
  CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS SALES_INTELLIGENCE.APP.WIDGETS (
  ID STRING PRIMARY KEY,
  DASHBOARD_ID STRING,
  CHAT_ID STRING,
  TITLE STRING,
  SPEC VARIANT,             -- chart spec produced by the render-chart skill
  POSITION INT,
  CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS SALES_INTELLIGENCE.APP.INTEGRATIONS (
  ID STRING PRIMARY KEY,
  KIND STRING,              -- snowflake_mcp | slack | email
  NAME STRING,
  CONFIG VARIANT,
  ENABLED BOOLEAN DEFAULT TRUE,
  CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- 2. Least-privilege role for the app
CREATE ROLE IF NOT EXISTS SALES_APP_ROLE;
GRANT ROLE SALES_APP_ROLE TO ROLE ACCOUNTADMIN;

GRANT USAGE ON WAREHOUSE SALES_INTELLIGENCE_WH TO ROLE SALES_APP_ROLE;
GRANT USAGE ON DATABASE SALES_INTELLIGENCE TO ROLE SALES_APP_ROLE;
GRANT USAGE ON SCHEMA SALES_INTELLIGENCE.DATA TO ROLE SALES_APP_ROLE;
GRANT USAGE ON SCHEMA SALES_INTELLIGENCE.APP TO ROLE SALES_APP_ROLE;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA SALES_INTELLIGENCE.APP TO ROLE SALES_APP_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE SALES_APP_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_AGENT_USER TO ROLE SALES_APP_ROLE;

-- Agent + its tools' underlying objects (agent runs with caller's rights)
GRANT USAGE ON MCP SERVER SALES_INTELLIGENCE.DATA.SALES_INTELLIGENCE_MCP TO ROLE SALES_APP_ROLE;
GRANT USAGE ON AGENT SALES_INTELLIGENCE.DATA.SALES_INTELLIGENCE_AGENT TO ROLE SALES_APP_ROLE;
GRANT USAGE ON CORTEX SEARCH SERVICE SALES_INTELLIGENCE.DATA.SALES_CONVERSATION_SEARCH TO ROLE SALES_APP_ROLE;
GRANT READ ON STAGE SALES_INTELLIGENCE.DATA.MODELS TO ROLE SALES_APP_ROLE;
GRANT SELECT ON TABLE SALES_INTELLIGENCE.DATA.SALES_METRICS TO ROLE SALES_APP_ROLE;
GRANT SELECT ON TABLE SALES_INTELLIGENCE.DATA.SALES_CONVERSATIONS TO ROLE SALES_APP_ROLE;
GRANT USAGE ON DATABASE DEFAULT_DATABASE TO ROLE SALES_APP_ROLE;
GRANT USAGE ON SCHEMA DEFAULT_DATABASE.PUBLIC TO ROLE SALES_APP_ROLE;
GRANT SELECT ON TABLE DEFAULT_DATABASE.PUBLIC.TESCO TO ROLE SALES_APP_ROLE;
-- Marketplace (imported) database: individual grants aren't allowed
GRANT IMPORTED PRIVILEGES ON DATABASE AMAZON_VENDOR_PL_FINANCE_REMITTANCE_AND_INVOICES_DEMO_DATASET TO ROLE SALES_APP_ROLE;

-- 3. Service user (PAT only). Vercel egress IPs are dynamic, so this user's
-- auth policy drops the network-policy requirement for PATs; any network policy
-- later attached to the user is still enforced.
CREATE AUTHENTICATION POLICY IF NOT EXISTS SALES_INTELLIGENCE.APP.SALES_APP_AUTH_POLICY
  AUTHENTICATION_METHODS = ('PROGRAMMATIC_ACCESS_TOKEN')
  PAT_POLICY = (NETWORK_POLICY_EVALUATION = ENFORCED_NOT_REQUIRED);

CREATE USER IF NOT EXISTS SALES_APP_SVC
  TYPE = SERVICE
  DEFAULT_ROLE = SALES_APP_ROLE
  DEFAULT_WAREHOUSE = SALES_INTELLIGENCE_WH
  COMMENT = 'snowflake-agent-hub Next.js app';
GRANT ROLE SALES_APP_ROLE TO USER SALES_APP_SVC;
ALTER USER SALES_APP_SVC SET AUTHENTICATION POLICY SALES_INTELLIGENCE.APP.SALES_APP_AUTH_POLICY;

