-- 01_setup.sql: database, schemas, warehouse and roles for Amazon Vendor Finance.
-- Run as ACCOUNTADMIN. Safe to re-run.

USE ROLE ACCOUNTADMIN;

-- Roles
CREATE ROLE IF NOT EXISTS AMZ_FIN_ADMIN COMMENT = 'Owns all Amazon Vendor Finance objects';
CREATE ROLE IF NOT EXISTS AMZ_FIN_USER  COMMENT = 'Reads finance data, uses the agent, manages action items';
CREATE ROLE IF NOT EXISTS AMZ_FIN_APP   COMMENT = 'Service role for the Next.js app';

GRANT ROLE AMZ_FIN_USER  TO ROLE AMZ_FIN_ADMIN;
GRANT ROLE AMZ_FIN_APP   TO ROLE AMZ_FIN_ADMIN;
GRANT ROLE AMZ_FIN_ADMIN TO ROLE SYSADMIN;

SET my_user = CURRENT_USER();
GRANT ROLE AMZ_FIN_ADMIN TO USER IDENTIFIER($my_user);

-- Warehouse
CREATE WAREHOUSE IF NOT EXISTS AMZ_FIN_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Amazon Vendor Finance: app, agent and pipeline queries';
GRANT OWNERSHIP ON WAREHOUSE AMZ_FIN_WH TO ROLE AMZ_FIN_ADMIN COPY CURRENT GRANTS;
GRANT USAGE ON WAREHOUSE AMZ_FIN_WH TO ROLE AMZ_FIN_USER;
GRANT USAGE ON WAREHOUSE AMZ_FIN_WH TO ROLE AMZ_FIN_APP;

-- Account-level privileges the admin role needs
GRANT EXECUTE TASK, EXECUTE ALERT ON ACCOUNT TO ROLE AMZ_FIN_ADMIN;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER       TO ROLE AMZ_FIN_ADMIN;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER       TO ROLE AMZ_FIN_USER;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_AGENT_USER TO ROLE AMZ_FIN_USER;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_AGENT_USER TO ROLE AMZ_FIN_APP;

-- Source data: the Marketplace share (read-only)
GRANT IMPORTED PRIVILEGES ON DATABASE AMAZON_VENDOR_PL_FINANCE_REMITTANCE_AND_INVOICES_DEMO_DATASET TO ROLE AMZ_FIN_ADMIN;

-- Database and schemas, owned by the admin role
CREATE DATABASE IF NOT EXISTS AMAZON_FINANCE_APP COMMENT = 'Amazon Vendor Finance platform';
GRANT OWNERSHIP ON DATABASE AMAZON_FINANCE_APP TO ROLE AMZ_FIN_ADMIN COPY CURRENT GRANTS;

USE ROLE AMZ_FIN_ADMIN;
USE DATABASE AMAZON_FINANCE_APP;
CREATE SCHEMA IF NOT EXISTS STAGING  COMMENT = 'Clean views over the shared source tables';
CREATE SCHEMA IF NOT EXISTS SEMANTIC COMMENT = 'Semantic views';
CREATE SCHEMA IF NOT EXISTS MARTS    COMMENT = 'Dashboard tables, insights and recommendations (app interface)';
CREATE SCHEMA IF NOT EXISTS APP      COMMENT = 'Agent and MCP server';
CREATE SCHEMA IF NOT EXISTS OPS      COMMENT = 'Action items, procedures, alerts and search';
DROP SCHEMA IF EXISTS PUBLIC;

-- Read access for users and the app (MARTS, SEMANTIC, APP are interface schemas)
GRANT USAGE ON DATABASE AMAZON_FINANCE_APP TO ROLE AMZ_FIN_USER;
GRANT USAGE ON DATABASE AMAZON_FINANCE_APP TO ROLE AMZ_FIN_APP;
GRANT USAGE ON SCHEMA MARTS    TO ROLE AMZ_FIN_USER;
GRANT USAGE ON SCHEMA MARTS    TO ROLE AMZ_FIN_APP;
GRANT USAGE ON SCHEMA SEMANTIC TO ROLE AMZ_FIN_USER;
GRANT USAGE ON SCHEMA APP      TO ROLE AMZ_FIN_USER;
GRANT USAGE ON SCHEMA APP      TO ROLE AMZ_FIN_APP;
GRANT USAGE ON SCHEMA OPS      TO ROLE AMZ_FIN_USER;
GRANT USAGE ON SCHEMA OPS      TO ROLE AMZ_FIN_APP;
GRANT SELECT ON ALL TABLES         IN SCHEMA MARTS TO ROLE AMZ_FIN_USER;
GRANT SELECT ON FUTURE TABLES      IN SCHEMA MARTS TO ROLE AMZ_FIN_USER;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA MARTS TO ROLE AMZ_FIN_USER;
GRANT SELECT ON FUTURE TABLES      IN SCHEMA MARTS TO ROLE AMZ_FIN_APP;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA MARTS TO ROLE AMZ_FIN_APP;
GRANT SELECT ON FUTURE VIEWS       IN SCHEMA MARTS TO ROLE AMZ_FIN_APP;
GRANT SELECT ON FUTURE VIEWS       IN SCHEMA MARTS TO ROLE AMZ_FIN_USER;
